"""Small, independently loadable PyTorch research models.

This module never imports Evo 2. Student inference requires only PyTorch.
"""
from __future__ import annotations

from typing import Sequence

import torch
from torch import nn


def one_hot(sequences: Sequence[str]) -> torch.Tensor:
    """Strict A/C/G/T one-hot encoding, returned as (batch, 4, length)."""
    if not sequences or not sequences[0]:
        raise ValueError("At least one nonempty DNA sequence is required")
    length = len(sequences[0])
    table = {base: i for i, base in enumerate("ACGT")}
    values = []
    for sequence in sequences:
        if len(sequence) != length:
            raise ValueError("All DNA sequences must have the same length")
        try:
            values.append([table[base] for base in sequence.upper()])
        except KeyError as exc:
            raise ValueError("Only A/C/G/T contexts are supported") from exc
    return torch.nn.functional.one_hot(torch.tensor(values), num_classes=4).permute(0, 2, 1).float()


class TeacherMLP(nn.Module):
    def __init__(self, input_dim: int, hidden_dims: Sequence[int] = (256, 64), dropout: float = 0.2):
        super().__init__()
        if input_dim <= 0 or not hidden_dims or any(int(x) <= 0 for x in hidden_dims):
            raise ValueError("Model dimensions must be positive")
        self.register_buffer("input_mean", torch.zeros(input_dim))
        self.register_buffer("input_scale", torch.ones(input_dim))
        layers: list[nn.Module] = []
        previous = input_dim
        for i, width in enumerate(hidden_dims):
            layers.extend([nn.Linear(previous, int(width)), nn.GELU()])
            if i == 0:
                layers.append(nn.Dropout(dropout))
            previous = int(width)
        layers.append(nn.Linear(previous, 1))
        self.net = nn.Sequential(*layers)

    @torch.no_grad()
    def fit_normalizer(self, training_features: torch.Tensor) -> None:
        if training_features.ndim != 2 or not torch.isfinite(training_features).all():
            raise ValueError("Expected finite (N, feature_dim) training features")
        self.input_mean.copy_(training_features.mean(dim=0))
        self.input_scale.copy_(training_features.std(dim=0, unbiased=False).clamp_min(1e-6))

    def forward(self, features: torch.Tensor) -> torch.Tensor:
        return self.net((features - self.input_mean) / self.input_scale).squeeze(-1)


class TinyStudent(nn.Module):
    def __init__(self, embedding_dim: int = 64, channels: Sequence[int] = (32, 64, 96), dropout: float = 0.2):
        super().__init__()
        if embedding_dim <= 0 or not channels or any(int(c) <= 0 for c in channels):
            raise ValueError("Student dimensions must be positive")
        layers: list[nn.Module] = []
        previous = 4
        for i, width in enumerate(channels):
            kernel = 7 if i == 0 else 5
            layers.extend([nn.Conv1d(previous, int(width), kernel_size=kernel, padding=kernel // 2), nn.GELU()])
            previous = int(width)
        self.encoder = nn.Sequential(*layers)
        self.embedding = nn.Linear(2 * previous, embedding_dim)
        self.feature_dim = 3 * embedding_dim
        self.head = nn.Sequential(nn.Linear(self.feature_dim, 128), nn.GELU(), nn.Dropout(dropout),
                                  nn.Linear(128, 32), nn.GELU(), nn.Linear(32, 1))
        if sum(p.numel() for p in self.parameters()) >= 2_000_000:
            raise ValueError("Student inference model must contain fewer than 2 million parameters")

    def encode(self, sequence: torch.Tensor) -> torch.Tensor:
        if sequence.ndim != 3 or sequence.shape[1] != 4:
            raise ValueError("Student input must have shape (B, 4, L)")
        value = self.encoder(sequence)
        pooled = torch.cat([value.mean(dim=-1), value.amax(dim=-1)], dim=-1)
        return self.embedding(pooled)

    def forward(self, reference: torch.Tensor, alternate: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        ref, alt = self.encode(reference), self.encode(alternate)
        fused = torch.cat([ref, alt, alt - ref], dim=-1)
        return self.head(fused).squeeze(-1), fused


def load_checkpoint(path, device="cpu") -> dict:
    """Load only tensor/primitive checkpoints generated by this project."""
    value = torch.load(path, map_location=device, weights_only=True)
    if not isinstance(value, dict) or value.get("kind") not in {"teacher", "student"}:
        raise ValueError("Unsupported project checkpoint")
    return value


def build_teacher(checkpoint: dict, device="cpu") -> TeacherMLP:
    if checkpoint.get("kind") != "teacher":
        raise ValueError("A teacher checkpoint is required")
    model = TeacherMLP(checkpoint["input_dim"], **checkpoint["model_kwargs"])
    model.load_state_dict(checkpoint["model_state"])
    return model.to(device).eval()


def build_student(checkpoint: dict, device="cpu") -> TinyStudent:
    if checkpoint.get("kind") != "student":
        raise ValueError("A student checkpoint is required")
    model = TinyStudent(**checkpoint["model_kwargs"])
    model.load_state_dict(checkpoint["model_state"])
    return model.to(device).eval()
